// Builds public/images/fa-icons.svg — an SVG sprite of the Font Awesome icons
// in lib/iconMap.js — for code that can't import npm packages: the plain-JS
// page scripts (G.icon in public/js/core.js) and the legacy EJS views.
// Run after changing lib/iconMap.js:  npm run icons:build

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import iconMap from '../lib/iconMap.js';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'public', 'images', 'fa-icons.svg');

const symbols = Object.entries(iconMap).map(([name, def]) => {
  const [width, height, , , svgPath] = def.icon;
  const paths = (Array.isArray(svgPath) ? svgPath : [svgPath]).map((d) => `<path d="${d}"/>`).join('');
  return `  <symbol id="${name}" viewBox="0 0 ${width} ${height}">${paths}</symbol>`;
});

fs.writeFileSync(
  out,
  `<!-- Generated by scripts/build-icon-sprite.mjs from lib/iconMap.js. Do not edit by hand. -->
<!-- Font Awesome Free by @fontawesome - https://fontawesome.com License - https://fontawesome.com/license/free -->
<svg xmlns="http://www.w3.org/2000/svg" style="display:none">
${symbols.join('\n')}
</svg>
`
);
console.log(`Wrote ${symbols.length} icons to ${path.relative(root, out)}`);
